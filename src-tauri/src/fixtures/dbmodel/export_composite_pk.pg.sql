-- Lumen schema export
-- PostgreSQL 17 / Supabase. Row level security is enabled on every table.
-- No policies are generated: the anon and authenticated roles can read or
-- write nothing until you add policies (see docs/SUPABASE.md).
-- Prefer Supabase Auth for login; treat app users tables as profiles, not
-- password stores.

create table public.projects (
  tenant_id uuid not null,
  code text not null,
  title text,
  constraint projects_pkey primary key (tenant_id, code)
);

create table public.tasks (
  id bigint generated by default as identity not null,
  tenant_id uuid not null,
  project_code text not null,
  seq bigint,
  constraint tasks_pkey primary key (id)
);

create table public.tenants (
  id uuid default gen_random_uuid() not null,
  constraint tenants_pkey primary key (id)
);

alter table public.projects add constraint projects_tenant_id_fkey foreign key (tenant_id) references public.tenants (id) on delete no action;
alter table public.tasks add constraint tasks_tenant_id_project_code_fkey foreign key (tenant_id, project_code) references public.projects (tenant_id, code) on delete cascade;
alter table public.tasks add constraint tasks_tenant_id_fkey foreign key (tenant_id) references public.tenants (id) on delete restrict;

create index tasks_tenant_id_project_code_idx on public.tasks (tenant_id, project_code);
create index tasks_tenant_id_idx on public.tasks (tenant_id);

alter table public.projects enable row level security;
alter table public.tasks enable row level security;
alter table public.tenants enable row level security;
