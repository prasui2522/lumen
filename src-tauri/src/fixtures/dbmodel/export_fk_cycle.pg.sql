-- Lumen schema export
-- PostgreSQL 17 / Supabase. Row level security is enabled on every table.
-- No policies are generated: the anon and authenticated roles can read or
-- write nothing until you add policies (see docs/SUPABASE.md).
-- Prefer Supabase Auth for login; treat app users tables as profiles, not
-- password stores.

create table public.departments (
  id uuid default gen_random_uuid() not null,
  head_id uuid not null,
  constraint departments_pkey primary key (id)
);

create table public.invites (
  id bigint generated by default as identity not null,
  email text not null,
  constraint invites_pkey primary key (id)
);

create table public.people (
  id uuid default gen_random_uuid() not null,
  email text not null,
  department_id uuid,
  constraint people_pkey primary key (id),
  constraint people_email_key unique (email)
);

alter table public.departments add constraint departments_head_id_fkey foreign key (head_id) references public.people (id) on delete restrict;
alter table public.invites add constraint invites_email_fkey foreign key (email) references public.people (email) on delete cascade;
alter table public.invites add constraint invites_email_fkey_7884fd36 foreign key (email) references public.people (email) on delete no action;
alter table public.people add constraint people_department_id_fkey foreign key (department_id) references public.departments (id) on delete set null;

create index departments_head_id_idx on public.departments (head_id);
create index invites_email_idx on public.invites (email);
create index people_department_id_idx on public.people (department_id);

alter table public.departments enable row level security;
alter table public.invites enable row level security;
alter table public.people enable row level security;
