-- Vite Studio schema export
-- PostgreSQL 17 / Supabase. Row level security is enabled on every table.
-- No policies are generated: the anon and authenticated roles can read or
-- write nothing until you add policies (see docs/SUPABASE.md).
-- Prefer Supabase Auth for login; treat app users tables as profiles, not
-- password stores.

create table public."row" (
  id bigint generated by default as identity not null,
  values_id uuid,
  "integer" bigint default 007,
  constraint row_pkey primary key (id)
);

create table public."values" (
  id uuid default gen_random_uuid() not null,
  "position" bigint default +5,
  "time" timestamptz,
  "json" jsonb,
  "between" text,
  constraint values_pkey primary key (id),
  constraint values_position_time_key unique ("position", "time"),
  constraint values_between_check check ("between" in ('a', 'b'))
);

alter table public."row" add constraint row_values_id_fkey foreign key (values_id) references public."values" (id) on delete set null;

create index row_values_id_idx on public."row" (values_id);

comment on table public."values" is 'ค่า';
comment on column public."values"."between" is 'ช่วง';

alter table public."row" enable row level security;
alter table public."values" enable row level security;
