-- Web Builder schema export
-- PostgreSQL 17. Row level security is enabled on every table.
-- No policies are generated: the anon and authenticated roles can read or
-- write nothing until you add policies.

create table public.employees (
  id bigint generated by default as identity not null,
  name text not null,
  manager_id bigint,
  mentor_id bigint,
  constraint employees_pkey primary key (id)
);

alter table public.employees add constraint employees_manager_id_fkey foreign key (manager_id) references public.employees (id) on delete set null;
alter table public.employees add constraint employees_mentor_id_fkey foreign key (mentor_id) references public.employees (id) on delete no action;

create index employees_manager_id_idx on public.employees (manager_id);
create index employees_mentor_id_idx on public.employees (mentor_id);

comment on table public.employees is 'พนักงาน';

alter table public.employees enable row level security;
