/**
 * Vite export helpers: generate AuthAdapter wiring + dbSubmit handler stubs.
 * Pages stay vendor-free; deploy swaps the adapter module.
 */
import type { DbModel } from "@/lib/db-model";

/** Source text shipped beside the exported site (src/lib/wb-db-runtime.ts). */
export function generateWbDbRuntimeSource(model: DbModel): string {
  const tables = model.tables.map((t) => ({
    id: t.id,
    name: t.name,
    primaryKey: t.primaryKey,
    columns: t.columns.map((c) => ({
      id: c.id,
      name: c.name,
      type: c.type,
      secret: c.secret ?? null,
      nullable: c.nullable,
    })),
    foreignKeys: t.foreignKeys.map((fk) => ({
      id: fk.id,
      columns: fk.columns,
      refTableId: fk.refTableId,
      refColumns: fk.refColumns,
    })),
  }));

  return `/* Generated by Vite Studio — Form↔DB runtime stub (reference only).
 * Prefer the shipped wb-db-runtime.ts + wb-db-supabase.ts with VITE_WB_DB_BACKEND=supabase.
 * See docs/SUPABASE.md and docs/FORM-DB-CRUD-SPEC.md.
 */
export const WB_DB_MODEL = ${JSON.stringify({ version: model.version, tables }, null, 2)} as const;

const SESSION_KEY = "wb.auth.session";

export async function stubHashPassword(plain) {
  const data = new TextEncoder().encode("wb:argon2id-stub:" + plain);
  const digest = await crypto.subtle.digest("SHA-256", data);
  const hex = [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
  return "$wb$v1$stub$" + hex;
}

export function createStubAuthAdapter() {
  return {
    hashPassword: stubHashPassword,
    async verifyPassword(plain, hash) {
      return (await stubHashPassword(plain)) === hash;
    },
    async signIn(identity, password) {
      const raw = sessionStorage.getItem("wb.auth.users");
      const users = raw ? JSON.parse(raw) : [];
      const user = users.find((u) => u.identity === identity);
      if (!user) return { ok: false, error: "ไม่พบผู้ใช้" };
      if ((await stubHashPassword(password)) !== user.passwordHash) {
        return { ok: false, error: "รหัสผ่านไม่ถูกต้อง" };
      }
      sessionStorage.setItem(SESSION_KEY, JSON.stringify({ identity }));
      return { ok: true };
    },
    async signOut() {
      sessionStorage.removeItem(SESSION_KEY);
    },
    session() {
      try {
        const s = JSON.parse(sessionStorage.getItem(SESSION_KEY) || "null");
        return s?.identity ? s : null;
      } catch {
        return null;
      }
    },
    requireSession() {
      return this.session() !== null;
    },
  };
}

export const auth = createStubAuthAdapter();

/** Guard /admin/* routes — call from SitePage or a layout wrapper. */
export function guardAdminPath(pathname) {
  if (!pathname.startsWith("/admin")) return true;
  if (auth.requireSession()) return true;
  if (typeof window !== "undefined") window.location.assign("/login");
  return false;
}
`;
}

/** site.json companion: list of admin paths that need session. */
export function adminProtectedPaths(model: DbModel): string[] {
  const paths = ["/admin"];
  for (const t of model.tables) {
    paths.push(`/admin/${t.name}`, `/admin/${t.name}/new`, `/admin/${t.name}/edit`);
  }
  return paths;
}
