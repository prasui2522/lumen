export function kindLabel(type: NodeType, locale: Locale): string {
  return locale === "en" ? EN[type] : TH[type];
}

export function useKindLabel(): (type: NodeType) => string {
  const locale = useLocale();
  return (type) => kindLabel(type, locale);
}
