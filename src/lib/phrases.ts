export function phrase(locale: Locale, th: string): string {
  if (locale === "th") return th;
  return EN[th] ?? th;
}

export function phraseCount(locale: Locale, n: number, thUnit: string, enUnit: string): string {
  if (locale === "th") return `พบ ${n} ${thUnit}`;
  return `${n} ${enUnit}`;
}

export function usePhrase(): (th: string) => string {
  const locale = useLocale();
  return useCallback((th: string) => phrase(locale, th), [locale]);
}
